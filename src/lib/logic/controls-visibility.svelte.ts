// ============================================================================
// controls-visibility.svelte.ts — Показ и автоскрытие панели управления
// ============================================================================
// Панель живёт секунду после последнего действия пользователя и прячется
// вместе с курсором. Но у неё есть режим, в котором прятаться нельзя, и
// раньше он назывался isDragging — по первому из поводов, а поводов набралось
// четыре, и все не про «перетаскивание»:
//
//   - тянут ползунок прогресс-бара,
//   - перематывают перетаскиванием по кадру,
//   - держат ← / → или крайнюю зону кадра (мышь при этом не двигается вовсе,
//     и без закрепления бар исчез бы прямо посреди перемотки),
//   - курсор просто лежит на самой панели.
//
// Поэтому здесь два разных «не прячься»: pin/unpin для идущего жеста и
// hoverStart/hoverEnd для курсора над панелью. Общее у них то, что при
// взведённом флаге keepAlive() показывает панель, но таймер не заводит.
//
// isPinned читает ещё и отрисовка: закреплённая панель означает «жест идёт»,
// а значит метку на прогресс-баре нужно вести по кадрам, а не по редкому
// timeupdate (см. displayTime в VideoPlayer.svelte).
// ============================================================================

// Сколько панель висит после последнего действия
const AUTOHIDE_MS = 1000;

export class ControlsVisibility {
    // $state — от этого зависит отрисовка панели и курсора
    private shown = $state(false);
    private pinned = $state(false);

    // Курсор над панелью. Обычное поле: наружу видно только через поведение
    // автоскрытия, отдельная реактивность не нужна.
    private hovered = false;

    private timer: ReturnType<typeof setTimeout> | undefined;

    /** Показывать ли панель сейчас. */
    get isVisible() {
        return this.shown;
    }

    /** Идёт ли жест, который держит панель на экране. */
    get isPinned() {
        return this.pinned;
    }

    /**
     * Пользователь что-то сделал: показываем панель и заводим автоскрытие
     * заново. Если панель закреплена жестом или под курсором — таймер не
     * заводим, она останется висеть.
     */
    keepAlive() {
        this.shown = true;
        clearTimeout(this.timer);

        if (this.pinned || this.hovered) return;

        this.timer = setTimeout(() => {
            this.shown = false;
        }, AUTOHIDE_MS);
    }

    /** Начался жест — панель на экран и держим, пока он не кончится. */
    pin() {
        this.pinned = true;
        this.shown = true;
        clearTimeout(this.timer);
    }

    /** Жест закончился — отпускаем панель и заводим автоскрытие заново. */
    unpin() {
        this.pinned = false;
        this.keepAlive();
    }

    /** Курсор вошёл на панель — под курсором она не прячется. */
    hoverStart() {
        this.hovered = true;
        clearTimeout(this.timer);
    }

    /** Курсор ушёл с панели — автоскрытие снова в силе. */
    hoverEnd() {
        this.hovered = false;
        this.keepAlive();
    }

    /**
     * Показать панель без автоскрытия.
     * Для состояний, а не действий: видео кончилось, идёт восстановление
     * после сбоя декодера — там панель должна остаться на экране.
     */
    show() {
        this.shown = true;
        clearTimeout(this.timer);
    }

    /** Курсор покинул окно — прячем сразу, не дожидаясь таймера. */
    hide() {
        clearTimeout(this.timer);
        this.shown = false;
    }

    /** Снятие таймера при уничтожении компонента. */
    cleanup() {
        clearTimeout(this.timer);
    }
}
