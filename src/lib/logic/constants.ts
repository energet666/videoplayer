// ============================================================================
// constants.ts — Константы, общие для нескольких обработчиков ввода
// ============================================================================
// Сюда вынесены только те значения, которые обязаны совпадать в разных
// модулях: разъехавшись, они ломают арбитраж жестов молча, без ошибки.
// Значения, живущие внутри одного обработчика (шаг перемотки назад, тайминги
// восстановления), остаются в своих файлах.
// ============================================================================

/**
 * Сколько секунд перемотки даёт один пиксель горизонтального движения.
 * Общая чувствительность перемотки перетаскиванием (drag-seek.svelte.ts) и
 * свайпа по тачпаду (touchpad.svelte.ts): 100px = 5 секунд. Жесты должны
 * ощущаться одинаково, поэтому коэффициент один на оба.
 */
export const SEEK_SECONDS_PER_PIXEL = 0.05;

/**
 * Порог в пикселях, отделяющий клик от перемотки перетаскиванием.
 * Одно и то же число для обоих участников арбитража левой кнопки:
 * drag-seek.svelte.ts начинает перемотку, перейдя порог, а
 * hold-zones.svelte.ts на том же пороге отдаёт ему жест. Разные значения
 * дали бы мёртвую зону (оба ждут) или двойной жест (оба сработали).
 */
export const GESTURE_MOVE_THRESHOLD_PX = 6;

/**
 * Сколько держать, чтобы нажатие перестало быть коротким.
 * Общее для клавиатуры (keyboard.svelte.ts: пробел и ←/→) и удержания левой
 * кнопки по зонам кадра (hold-zones.svelte.ts) — оба запускают одни и те же
 * длинные действия из hold-actions.ts, и порог у них должен быть один.
 */
export const HOLD_DELAY_MS = 200;

/**
 * Шаг перемотки двойным кликом по половине кадра.
 * Общий для click-seek.ts (реальная перемотка) и seek-indicator.svelte.ts
 * (единица накопления в серии: −10, −20, −30…) — показанное число должно
 * складываться ровно из тех шагов, которые сделало видео.
 */
export const CLICK_SEEK_SECONDS = 10;
